"""
AI Cold Outreach Modal Dialog Component.
Enables generating personalized emails via Gemini and dispatching them via SMTP.
"""
from typing import Dict, Any, Callable
import flet as ft

from app.flet_app.config import (
    SURFACE_CARD, SURFACE_ELEVATED, SURFACE_BORDER,
    TEXT_PRIMARY, TEXT_SECONDARY, TEXT_MUTED,
    ACCENT_INDIGO, ACCENT_CYAN, ACCENT_GREEN, ACCENT_RED
)
from app.flet_app.api_client import api_client
from app.flet_app.components.toast import show_toast


def open_outreach_modal(page: ft.Page, opportunity: Dict[str, Any]):
    """Opens a modal dialog to draft and send cold outreach to company recruiters."""
    
    company = opportunity.get("company", "Company")
    title = opportunity.get("title", "Position")
    summary = opportunity.get("summary", "")

    recipient_name_field = ft.TextField(
        label="Recipient Name (Optional)",
        hint_text="e.g. Hiring Manager, John Doe",
        value="",
        bgcolor=SURFACE_CARD,
        border_color=SURFACE_BORDER,
        color=TEXT_PRIMARY,
        text_size=13,
        expand=True,
    )

    recipient_email_field = ft.TextField(
        label="Recipient Email",
        hint_text="e.g. careers@company.com or recruiter@company.com",
        value=opportunity.get("contact_email", ""),
        bgcolor=SURFACE_CARD,
        border_color=SURFACE_BORDER,
        color=TEXT_PRIMARY,
        text_size=13,
        expand=True,
    )

    subject_field = ft.TextField(
        label="Subject Line",
        value=f"Application for {title} — CareerPulse Candidate",
        bgcolor=SURFACE_CARD,
        border_color=SURFACE_BORDER,
        color=TEXT_PRIMARY,
        text_size=13,
    )

    body_field = ft.TextField(
        label="Email Message (Generated by Gemini AI)",
        hint_text="Click 'Generate with AI' to draft a tailored letter...",
        value="",
        multiline=True,
        min_lines=8,
        max_lines=12,
        bgcolor=SURFACE_CARD,
        border_color=SURFACE_BORDER,
        color=TEXT_PRIMARY,
        text_size=13,
    )

    status_text = ft.Text("", size=12, color=ACCENT_CYAN)
    loading_indicator = ft.ProgressRing(width=16, height=16, stroke_width=2, color=ACCENT_CYAN, visible=False)

    async def generate_draft(e):
        loading_indicator.visible = True
        status_text.value = "Generating personalized draft with Gemini AI..."
        page.update()
        try:
            req_data = {
                "company": company,
                "title": title,
                "summary": summary,
                "recipient_name": recipient_name_field.value.strip(),
                "recipient_email": recipient_email_field.value.strip() or "recruiter@company.com",
            }
            res = await api_client.generate_email_draft(req_data)
            if res.get("status") == "success" or res.get("body"):
                body_field.value = res.get("body", "")
                if res.get("subject"):
                    subject_field.value = res.get("subject")
                status_text.value = "Draft generated! Review before sending."
                status_text.color = ACCENT_GREEN
            else:
                status_text.value = res.get("detail", "Could not generate draft.")
                status_text.color = ACCENT_RED
        except Exception as err:
            status_text.value = f"Generation error: {err}"
            status_text.color = ACCENT_RED
        finally:
            loading_indicator.visible = False
            page.update()

    async def send_outreach(e):
        to_email = recipient_email_field.value.strip()
        if not to_email or "@" not in to_email:
            show_toast(page, "Please enter a valid recipient email address.", is_error=True)
            return

        loading_indicator.visible = True
        status_text.value = "Dispatching email via SMTP..."
        page.update()
        try:
            send_req = {
                "to_email": to_email,
                "subject": subject_field.value.strip(),
                "body": body_field.value.strip(),
                "opportunity_id": f"{company}_{title}".lower().replace(" ", "_"),
                "company": company,
                "title": title,
            }
            res = await api_client.send_email(send_req)
            if res.get("status") == "success":
                show_toast(page, f"Application outreach successfully sent to {to_email}!")
                dlg.open = False
                page.update()
            else:
                status_text.value = res.get("detail", "Failed to send email.")
                status_text.color = ACCENT_RED
        except Exception as err:
            status_text.value = f"Send error: {err}"
            status_text.color = ACCENT_RED
        finally:
            loading_indicator.visible = False
            page.update()

    def close_modal(e):
        dlg.open = False
        page.update()

    dlg = ft.AlertDialog(
        modal=True,
        title=ft.Row(
            controls=[
                ft.Icon(ft.Icons.AUTO_AWESOME, color=ACCENT_INDIGO, size=20),
                ft.Text(f"AI Cold Outreach: {company}", size=17, weight=ft.FontWeight.BOLD, color=TEXT_PRIMARY),
            ],
            spacing=8,
        ),
        content=ft.Container(
            content=ft.Column(
                controls=[
                    ft.Text(f"Position: {title}", size=13, color=TEXT_SECONDARY),
                    ft.Container(height=6),
                    ft.Row(controls=[recipient_name_field, recipient_email_field], spacing=10),
                    ft.Container(height=6),
                    subject_field,
                    ft.Container(height=6),
                    body_field,
                    ft.Container(height=6),
                    ft.Row(controls=[loading_indicator, status_text], spacing=8),
                ],
                tight=True,
                scroll=ft.ScrollMode.AUTO,
            ),
            width=620,
            padding=10,
        ),
        actions=[
            ft.TextButton(
                "Cancel",
                on_click=close_modal,
                style=ft.ButtonStyle(color=TEXT_MUTED),
            ),
            ft.OutlinedButton(
                "Generate with AI",
                icon=ft.Icons.PSYCHOLOGY,
                on_click=generate_draft,
                style=ft.ButtonStyle(
                    color=ACCENT_INDIGO,
                    side=ft.BorderSide(1, ACCENT_INDIGO),
                ),
            ),
            ft.FilledButton(
                "Send Email",
                icon=ft.Icons.SEND,
                on_click=send_outreach,
                style=ft.ButtonStyle(
                    bgcolor=ACCENT_GREEN,
                    color=TEXT_PRIMARY,
                ),
            ),
        ],
        actions_alignment=ft.MainAxisAlignment.END,
        bgcolor=SURFACE_ELEVATED,
        open=True,
    )

    page.overlay.append(dlg)
    page.update()
